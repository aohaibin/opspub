import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const exportPath = path.join(root, "docs", "opspub-skills-export.md");
const indexPath = path.join(root, "docs", "skills-index-20261006.md");
const outputDir = path.join(root, "docs", "skills");
const rustOutputPath = path.join(root, "src-tauri", "src", "services", "mcp", "generated_skill_bodies.rs");

function parseSkillSections(markdown, allowedNames) {
  const headings = [...markdown.matchAll(/^## (\d+)\.\s+`?([^`\r\n]+?)`?\s*$/gm)]
    .filter((heading) => allowedNames.has(heading[2].trim()));
  return headings.flatMap((heading, index) => {
    const name = heading[2].trim();

    const start = heading.index + heading[0].length;
    const end = headings[index + 1]?.index ?? markdown.length;
    const section = markdown.slice(start, end);
    const yamlFence = section.match(/```yaml\s*\r?\n([\s\S]*?)\r?\n```/);
    if (!yamlFence) throw new Error(`skill ${name} has no YAML frontmatter block`);

    const frontmatterStart = section.indexOf(yamlFence[0]);
    const bodyStart = frontmatterStart + yamlFence[0].length;
    const body = section.slice(bodyStart).replace(/^\r?\n+/, "").trimEnd();
    const skill = `${yamlFence[1].trimEnd()}\n\n${body}\n`;
    if (!body.trim()) throw new Error(`skill ${name} has an empty body`);
    return [{ name, content: skill }];
  });
}

function parseIndexNames(markdown) {
  return [...markdown.matchAll(/^## (\d+)\.\s+`?([^`\r\n]+?)`?\s*$/gm)]
    .map((match) => ({ number: Number(match[1]), name: match[2] }))
    .filter((entry) => entry.number >= 1 && entry.number <= 41);
}

const indexedSkills = parseIndexNames(fs.readFileSync(indexPath, "utf8"));
const allowedNames = new Set(indexedSkills.map((skill) => skill.name));
const exportedSkills = parseSkillSections(fs.readFileSync(exportPath, "utf8"), allowedNames);
if (exportedSkills.length !== 41 || indexedSkills.length !== 41) {
  throw new Error(`expected 41 bundled skills; export=${exportedSkills.length}, index=${indexedSkills.length}`);
}
const exportedByName = new Map(exportedSkills.map((skill) => [skill.name, skill]));
const missing = indexedSkills.filter((skill) => !exportedByName.has(skill.name));
const unexpected = exportedSkills.filter((skill) => !indexedSkills.some((item) => item.name === skill.name));
if (missing.length || unexpected.length) {
  throw new Error(`skill mismatch: missing=${missing.map((skill) => skill.name).join(",")}; unexpected=${unexpected.map((skill) => skill.name).join(",")}`);
}
const orderedSkills = indexedSkills.map((skill) => exportedByName.get(skill.name));

fs.mkdirSync(outputDir, { recursive: true });
for (const skill of orderedSkills) {
  fs.writeFileSync(path.join(outputDir, `${skill.name}.md`), skill.content, "utf8");
}

const rustBody = [
  "// Generated by scripts/generate-skill-bodies.mjs from docs/opspub-skills-export.md; do not edit manually.",
  "pub fn get(name: &str) -> Option<&'static str> {",
  "    match name {",
  ...orderedSkills.flatMap((skill) => [
    `        ${JSON.stringify(skill.name)} => Some(include_str!(concat!(`,
    `            env!(\"CARGO_MANIFEST_DIR\"),`,
    `            \"/../docs/skills/${skill.name}.md\"`,
    "        ))),",
  ]),
  "        _ => None,",
  "    }",
  "}",
  "",
].join("\n");
fs.writeFileSync(rustOutputPath, rustBody, "utf8");
console.log(`imported ${orderedSkills.length} individual built-in skills; excluded 2 user skills`);
